/**
 * Generates the typography stylesheets from lib/typography.ts and lib/font-presets.ts.
 *
 *   pnpm typography:build
 *
 * styles/typography.css (Inter)
 *   - :root custom properties  --inter-opsz-<size>-<weight> / --inter-ls-<size>-<weight>
 *   - @theme weight tokens     --font-weight-book (350), --font-weight-text (450)
 *   - @utility presets         inter-opt-<size>-<weight>  (upstream names; emitted only when used)
 *   - semantic styles          @utility text-<name>       (display, h1…, body, label…)
 *
 * styles/font-presets.css (every brand family)
 *   - @theme font families     --font-<id> with a var(--face-<id>) hook for the site's loader
 *   - :root custom properties  --<id>-ls-<size>-<weight> / --<id>-lh-<size>
 *   - @utility presets         <id>-opt-<size>-<weight>   (family + size + weight + leading + tracking)
 *
 * Runs on plain Node ≥ 22.6 (type stripping); no bundler or path aliases.
 */
import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

import {
  FONT_FAMILIES,
  familyFontVar,
  familyLhVar,
  familyLsVar,
  familyPreset,
  familyPresetClass,
  familyStack,
  familyWeights,
} from "../lib/font-presets.ts"
import {
  INTER_OPTICAL_PRESETS,
  PRESET_SIZES,
  PRESET_WEIGHTS,
  TYPE_SCALE,
  WEIGHT_TOKENS,
  isMeasuredWeight,
  lsVar,
  opszVar,
  presetClass,
  typeStyleClass,
  typeStyleDeclarations,
} from "../lib/typography.ts"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")

const px = (value: number) => `${value}px`

const block = (selector: string, declarations: Record<string, string>) =>
  `${selector} {\n${Object.entries(declarations)
    .map(([property, value]) => `  ${property}: ${value};`)
    .join("\n")}\n}`

function write(file: string, lines: string[]) {
  const target = join(root, file)
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, `${lines.join("\n")}\n`)
  return target
}

// ---------------------------------------------------------------------------
// styles/typography.css — Inter optical sizing + semantic scale
// ---------------------------------------------------------------------------
{
  const lines: string[] = []

  lines.push(`/*
 * GENERATED by scripts/gen-typography-css.ts — do not edit by hand.
 * Edit lib/typography.ts and run \`pnpm typography:build\`.
 *
 * Inter optical sizing presets. Weights 400–700 are measured values from
 * nanxstats/inter-optical-sizing (MIT, © 2025 Nan Xiao), which tune Inter's
 * \`opsz\` axis and letter-spacing to match San Francisco. Weights 300 and 350
 * are extrapolated from the 400→450 slope for light display type.
 *
 * Requires the Inter variable font with the \`opsz\` axis (Inter 4.x; with
 * next/font/google pass axes: ["opsz"]).
 */`)

  lines.push("")
  lines.push(":root {")
  for (const size of PRESET_SIZES) {
    const row = INTER_OPTICAL_PRESETS[size]
    for (const weight of PRESET_WEIGHTS) {
      const { opsz, ls } = row[weight]
      const note = isMeasuredWeight(weight) ? "" : " /* extrapolated */"
      lines.push(`  ${opszVar(size, weight)}: ${opsz};${note}`)
      lines.push(`  ${lsVar(size, weight)}: ${ls === 0 ? "0" : px(ls)};`)
    }
  }
  lines.push("}")

  lines.push("")
  lines.push("@theme {")
  for (const token of WEIGHT_TOKENS) {
    if (token.builtIn) continue
    lines.push(`  --font-weight-${token.name}: ${token.weight};`)
  }
  lines.push("}")

  lines.push("")
  lines.push("/* Size × weight presets, same names as upstream: inter-opt-<size>-<weight>. Tailwind emits only the ones you use. */")
  for (const size of PRESET_SIZES) {
    const row = INTER_OPTICAL_PRESETS[size]
    for (const weight of PRESET_WEIGHTS) {
      const { ls } = row[weight]
      const declarations: Record<string, string> = {
        "font-size": px(size),
        "font-weight": String(weight),
        "font-variation-settings": `"opsz" var(${opszVar(size, weight)})`,
      }
      if (ls !== 0) declarations["letter-spacing"] = `var(${lsVar(size, weight)})`
      lines.push(block(`@utility ${presetClass(size, weight)}`, declarations))
    }
  }

  lines.push("")
  lines.push("/* Semantic scale. Each style pins one size × weight preset. */")
  for (const style of TYPE_SCALE) {
    lines.push(block(`@utility ${typeStyleClass(style)}`, typeStyleDeclarations(style)))
  }

  const target = write("styles/typography.css", lines)
  console.log(
    `Wrote ${target}: ${PRESET_SIZES.length} sizes × ${PRESET_WEIGHTS.length} weights, ${TYPE_SCALE.length} text styles.`,
  )
}

// ---------------------------------------------------------------------------
// styles/font-presets.css — per-family tracking + leading
// ---------------------------------------------------------------------------
{
  const families = FONT_FAMILIES.filter((family) => family.id !== "inter")
  const lines: string[] = []

  lines.push(`/*
 * GENERATED by scripts/gen-typography-css.ts — do not edit by hand.
 * Edit lib/font-presets.ts and run \`pnpm typography:build\`.
 *
 * Per-family presets for the brand's non-Inter faces. None of these has an
 * opsz axis, so each size × weight cell carries letter-spacing and
 * line-height only. Values are curves shaped like Inter's measured table
 * with per-family anchors chosen by eye — a starting point, not a measurement.
 *
 * Font loading is the site's job. Define --face-<id> (e.g. from next/font's
 * \`variable\`) and the @theme families below pick it up; otherwise they fall
 * back to the family name, which works with @fontsource imports.
 */`)

  lines.push("")
  lines.push("@theme {")
  for (const family of FONT_FAMILIES) {
    lines.push(`  ${familyFontVar(family)}: ${familyStack(family)};`)
  }
  lines.push("}")

  lines.push("")
  lines.push(":root {")
  for (const family of families) {
    lines.push(`  /* ${family.label} */`)
    for (const size of PRESET_SIZES) {
      lines.push(`  ${familyLhVar(family, size)}: ${familyPreset(family, size, 400).lineHeight};`)
      for (const weight of familyWeights(family)) {
        const { ls } = familyPreset(family, size, weight)
        lines.push(`  ${familyLsVar(family, size, weight)}: ${ls === 0 ? "0" : px(ls)};`)
      }
    }
  }
  lines.push("}")

  for (const family of families) {
    lines.push("")
    lines.push(`/* ${family.label}: ${family.id}-opt-<size>-<weight> */`)
    for (const size of PRESET_SIZES) {
      for (const weight of familyWeights(family)) {
        const { ls } = familyPreset(family, size, weight)
        const declarations: Record<string, string> = {
          "font-family": `var(${familyFontVar(family)})`,
          "font-size": px(size),
          "font-weight": String(weight),
          "line-height": `var(${familyLhVar(family, size)})`,
        }
        if (ls !== 0) declarations["letter-spacing"] = `var(${familyLsVar(family, size, weight)})`
        lines.push(block(`@utility ${familyPresetClass(family, size, weight)}`, declarations))
      }
    }
  }

  const target = write("styles/font-presets.css", lines)
  console.log(`Wrote ${target}: ${families.length} families × ${PRESET_SIZES.length} sizes.`)
}
